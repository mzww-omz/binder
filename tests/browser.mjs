// Self-contained for Playwright CLI's run-code; see README.
export async function run(page) {
  const equal = (actual, expected, message = 'Unexpected value') => {
    if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error(`${message}: ${JSON.stringify(actual)} !== ${JSON.stringify(expected)}`);
  };
  const origin = 'http://localhost:8787';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto(origin);
  await page.getByLabel('Theme', { exact: true }).selectOption('light');
  await page.screenshot({ path: '/tmp/binder-redesign-home.png', fullPage: true });
  await page.getByRole('button', { name: 'Create Binder', exact: true }).click();
  await page.waitForURL(/\/edit#[a-f0-9]{64}$/);
  const editURL = page.url(), shareURL = editURL.split('/edit#')[0];
  const id = shareURL.split('/').pop(), secret = editURL.split('#')[1];
  const apiURL = `${origin}/api/binders/${id}`;
  const initial = await (await page.request.get(apiURL)).json();
  const list = page.getByRole('list', { name: 'Folder contents', exact: true });
  const folder = name => list.getByRole('button', { name, exact: true });
  const actions = name => list.getByRole('button', { name: `Actions for ${name}`, exact: true });
  const choose = async (name, action) => {
    await actions(name).click();
    await page.getByRole('menuitem', { name: action, exact: true }).click();
    await page.locator('main[aria-busy="false"]').waitFor();
  };
  const newFolder = async name => {
    await page.getByRole('button', { name: 'New Folder', exact: true }).click();
    const input = page.getByRole('textbox', { name: 'Folder name', exact: true });
    equal(await input.evaluate(el => el === document.activeElement), true, 'folder name receives focus');
    await input.fill(name); await input.press('Enter'); await folder(name).waitFor();
  };
  const addLink = async (url, name) => {
    const input = page.getByRole('textbox', { name: 'Add a link', exact: true });
    await input.fill(url); await input.press('Enter');
    await list.getByRole('link', { name, exact: true }).waitFor();
    equal(await input.inputValue(), '');
    equal(await input.evaluate(el => el === document.activeElement), true, 'link input stays focused');
  };
  await page.getByRole('textbox', { name: 'Add a link', exact: true }).waitFor({ timeout: 5000 });
  equal(await page.getByRole('radio').count(), 0);
  equal(await page.getByRole('table').count(), 0);
  await page.screenshot({ path: '/tmp/binder-redesign-empty.png', fullPage: true });
  await page.getByRole('button', { name: 'New Folder', exact: true }).click();
  await page.getByRole('textbox', { name: 'Folder name', exact: true }).fill('Cancelled');
  await page.getByRole('textbox', { name: 'Folder name', exact: true }).press('Escape');
  equal(await page.getByRole('textbox', { name: 'Folder name', exact: true }).count(), 0);
  equal((await (await page.request.get(apiURL)).json()).nodes.length, 0, 'cancel must not create a folder');
  await newFolder('Projects');
  await addLink('https://example.com/notes', 'example.com');
  await addLink('https://developers.cloudflare.com/d1/', 'developers.cloudflare.com');
  await page.getByRole('button', { name: 'Share', exact: true }).click();
  await page.getByText('Share URL copied.', { exact: true }).waitFor();
  equal(await page.evaluate(() => navigator.clipboard.readText()), shareURL);
  equal(await page.getByRole('menuitem', { name: 'Copy edit URL', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Binder options', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Copy edit URL', exact: true }).click();
  await page.getByText('Edit URL copied. Keep it private.', { exact: true }).waitFor();
  equal(await page.evaluate(() => navigator.clipboard.readText()), editURL);
  equal(await page.locator('body').innerText().then(text => text.includes(secret)), false, 'secret must not be rendered');

  await choose('Projects', 'Rename');
  const rename = page.getByRole('textbox', { name: 'Folder name', exact: true });
  await rename.fill('Research');
  await page.route('**/api/binders/*/nodes/*', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Temporary test failure"}' }), { times: 1 });
  await rename.press('Enter');
  await page.getByText('Temporary test failure', { exact: true }).waitFor();
  equal(await rename.inputValue(), 'Research', 'failed rename retains input');
  await rename.press('Enter'); await folder('Research').waitFor();
  const heading = await page.locator('.binder-header').elementHandle();
  const composer = await page.getByRole('textbox', { name: 'Add a link', exact: true }).elementHandle();
  await folder('Research').click();
  await newFolder('References'); await folder('References').click();
  await newFolder('Sources'); await folder('Sources').click();
  equal(await heading.evaluate(el => el.isConnected), true, 'navigation preserves the header');
  equal(await composer.evaluate(el => el.isConnected), true, 'navigation preserves the URL input');
  await addLink('https://github.com/example', 'github.com');
  await choose('github.com', 'Edit');
  await page.getByLabel('Name', { exact: true }).fill('<img src=x onerror=alert(1)>');
  await page.getByLabel('URL', { exact: true }).fill('https://example.org/docs');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await list.getByRole('link', { name: '<img src=x onerror=alert(1)>', exact: true }).waitFor();
  equal(await page.locator('#app img').count(), 0);
  await choose('<img src=x onerror=alert(1)>', 'Rename');
  await page.getByRole('textbox', { name: 'Link name', exact: true }).fill('Documentation');
  await page.getByRole('textbox', { name: 'Link name', exact: true }).press('Enter');
  await list.getByRole('link', { name: 'Documentation', exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/binder-redesign-nested.png', fullPage: true });
  await page.goBack(); await folder('Sources').waitFor();
  await page.goForward(); await list.getByRole('link', { name: 'Documentation', exact: true }).waitFor();
  await page.getByRole('navigation', { name: 'Folders', exact: true }).getByRole('button', { name: 'References', exact: true }).click();
  await choose('Sources', 'Move');
  const destination = page.getByRole('combobox', { name: 'Destination', exact: true });
  equal(await destination.locator('option').allTextContents().then(options => options.some(text => text.endsWith('/ Sources'))), false, 'move excludes self and descendants');
  await destination.selectOption('');
  await page.getByRole('button', { name: 'Move here', exact: true }).click();
  await folder('Sources').waitFor({ state: 'detached' });
  await page.getByRole('navigation', { name: 'Folders', exact: true }).getByRole('button', { name: 'Binder', exact: true }).click();
  await folder('Sources').waitFor();
  await choose('Sources', 'Move up');
  await page.getByText('Order updated.', { exact: true }).waitFor();
  equal(await list.locator('.node-name').allTextContents(), ['Research', 'example.com', 'Sources', 'developers.cloudflare.com']);
  await choose('Sources', 'Move down');
  await page.getByText('Order updated.', { exact: true }).waitFor();
  equal(await list.locator('.node-name').allTextContents(), ['Research', 'example.com', 'developers.cloudflare.com', 'Sources']);
  await list.getByRole('link', { name: 'example.com', exact: true }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await actions('example.com').focus(); await page.keyboard.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).waitFor();
  await page.keyboard.press('End');
  equal(await page.getByRole('menuitem', { name: 'Delete', exact: true }).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Escape');
  equal(await actions('example.com').evaluate(el => el === document.activeElement), true);
  await page.screenshot({ path: '/tmp/binder-redesign-desktop.png', fullPage: true });

  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await page.screenshot({ path: '/tmp/binder-redesign-mobile.png', fullPage: true });
  await actions('developers.cloudflare.com').click();
  await page.screenshot({ path: '/tmp/binder-redesign-mobile-menu.png', fullPage: true });
  const menuBounds = await page.getByRole('menu').boundingBox();
  equal(menuBounds.x >= 0 && menuBounds.x + menuBounds.width <= 375, true, 'menu stays inside viewport');
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('A very long link name '.repeat(8));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await list.getByRole('link', { name: /^A very long link name/ }).waitFor();
  equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, '375px has no horizontal overflow');
  await page.getByLabel('Theme', { exact: true }).selectOption('system');
  await page.emulateMedia({ colorScheme: 'dark' });
  equal(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme), 'dark');
  await page.getByLabel('Theme', { exact: true }).selectOption('light');
  equal(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme), 'light');
  await page.reload(); await folder('Sources').waitFor();
  equal(await page.getByLabel('Theme', { exact: true }).inputValue(), 'light');
  await page.goto(shareURL);
  equal(await page.getByRole('textbox', { name: 'Add a link', exact: true }).count(), 0);
  equal(await page.getByRole('button', { name: /^Actions for / }).count(), 0);
  equal(await page.getByRole('button', { name: 'Binder options', exact: true }).count(), 0);
  await folder('Sources').click();
  const docs = list.getByRole('link', { name: 'Documentation', exact: true }); await docs.waitFor();
  equal(await docs.getAttribute('href'), 'https://example.org/docs');
  equal(await docs.getAttribute('rel'), 'noopener noreferrer');
  equal(await docs.getAttribute('target'), '_blank');
  await page.goto(editURL.replace(/#[^#]+$/, '#' + '0'.repeat(64)));
  await page.getByText('Invalid edit token', { exact: true }).waitFor();
  equal(await page.getByRole('textbox', { name: 'Add a link', exact: true }).count(), 0);
  await page.goto(editURL); await folder('Research').waitFor();
  await choose('Research', 'Delete');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await folder('Research').waitFor();
  await choose('Research', 'Delete');
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
  await folder('Research').waitFor({ state: 'detached' });
  const final = await (await page.request.get(apiURL)).json();
  equal(final.expires_at, initial.expires_at, 'UI edits must not extend expiry');
  await page.getByRole('button', { name: 'Binder options', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Delete Binder', exact: true }).click();
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
  await page.waitForURL(origin + '/');
  equal((await page.request.get(apiURL)).status(), 404);
  equal(errors, [], 'no unhandled browser exceptions');
}
